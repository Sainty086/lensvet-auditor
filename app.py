import streamlit as st
import google.generativeai as genai
import tempfile
import os

# ==========================================
# 1. НАСТРОЙКИ БЕЗОПАСНОСТИ И ДОСТУПА
# ==========================================
# Вставь сюда свой реальный API-ключ внутри кавычек
MY_API_KEY = st.secrets["GEMINI_API_KEY"] 

# Придумай пароль для коллег
APP_PASSWORD = "MartiniMartini" 


# ==========================================
# 2. ИНТЕРФЕЙС И ПРОВЕРКА ПАРОЛЯ
# ==========================================
# ИЗМЕНЕНИЕ 1: Убрали layout="wide". Теперь страница центрирована и ограничена ~730px (как ширина чата)
st.set_page_config(page_title="Аудитор Ленсвет", page_icon="💡", layout="centered")
st.title("🕵️‍♂️ ИИ-Аудитор паспортов светильников")

# ИЗМЕНЕНИЕ 2: Создаем колонки. Левая (input_col) займет 2/3 от 730px (примерно 480px).
input_col, empty_col = st.columns([2, 1])

with input_col:
    # Кладем поле пароля в узкую колонку
    user_password = st.text_input("🔒 Введите пароль для доступа:", type="password")

# Шлагбаум пароля
if user_password != APP_PASSWORD:
    st.warning("Пожалуйста, введите верный пароль для начала работы.")
    st.stop() 

st.success("Доступ разрешен!")
st.write("Загрузите паспорт в формате PDF, и система проверит его на соответствие требованиям СПб ГБУ «Ленсвет».")


# ==========================================
# 3. НАСТРОЙКА API И ПРОМПТ
# ==========================================
genai.configure(api_key=MY_API_KEY)

system_prompt = """
Ты — строгий технический эксперт-аудитор. Твоя главная база знаний — прикрепленный файл с техническими требованиями СПб ГБУ «Ленсвет». Твоя задача — проверить предоставленный пользователем паспорт (или техническое описание) светодиодного светильника или прожектора для архитектурно-художественной подсветки на полное соответствие этим требованиям.
При проверке всегда сверяйся с оригинальным прикрепленным файлом. Для структурирования аудита обязательно используй следующий чек-лист:

1. Обязательное наличие данных (п. 4.2):В паспорте должна присутствовать следующая информация:
Номер модели.
Класс светораспределения (для светильников) или тип (для прожекторов).
Тип кривой силы света (КСС).
Номинальная цветовая температура (КЦТ).
Мощность с учетом потерь.
Номинальное напряжение.
Предельно допустимая температура среды.
Световой поток и Световая отдача.
Амплитуда и длительность пускового тока.
Общий индекс цветопередачи (Ra).
Коэффициент мощности.
Степень защиты IP.
Габаритные размеры и масса.
Класс защиты от поражения электрическим током.
Гарантийный срок и срок службы.
Маркировка жил на клеммах.
Руководство по монтажу.
Параметры источника питания: номинальный ток, входное и выходное напряжение.
Угол раскрытия светового потока.

2. Энергоэффективность (п. 5.1):
Для светильников:
При Ra 70-80: < 4500K — от 90 Лм/Вт; >= 4500K — от 95 Лм/Вт.
При Ra 80-90: < 4500K — от 85 Лм/Вт; >= 4500K — от 90 Лм/Вт.
При Ra 90-100: < 4500K — от 70 Лм/Вт; >= 4500K — от 75 Лм/Вт.
Для прожекторов: узкое светораспределение — от 65 Лм/Вт, среднее — от 85 Лм/Вт, широкое — от 95 Лм/Вт.

3. Световые и электрические параметры (п. 6-7):
Снижение светового потока: не более 6%.
Коэффициент пульсации: не более 15%.
Питание: 230 В, 50 Гц. Диапазон: не хуже 176–264 В.
Защита драйвера: от КЗ, холостого хода, перегрева; наличие гальванической развязки.
Коэффициент мощности: до 8 Вт — от 0,7; 8–20 Вт — от 0,85; более 20 Вт — от 0,90.
Класс защиты (грунтовые): III.

4. Конструкция, стойкость и гарантия (п. 8-11):
Температура радиатора: не более 60°C.
Вес: не более 5 кг.
Наличие регулируемого кронштейна: Допускается указание поворотной «лиры», «скобы» или любого механизма наклона. Это важное, но не жесткое требование: если слова «кронштейн/лира» есть — это ✅ Соответствует. Если информации нет, ставь статус «⚠️ Отсутствует информация», но не выноси это в критические замечания для отказа.
Защитное стекло: силикатное.
Кабель питания: Проверяй наличие информации о кабеле. Он должен быть заявлен как стойкий к ультрафиолетовому излучению (УФ-стойкий), а его защитная оболочка должна быть черного цвета.
Разъем подключения: В случае применения для подключения светильника разъема, его степень защиты должна быть строго IP68.
IP: IP66 (выше 1,5 м) или IP68 (в грунте/воде).
Гарантия: от 5 лет.
Срок службы: от 12 лет.
Ресурс: от 50 000 часов.

5. Проверка нормативной терминологии и ГОСТов:
Обращай особое внимание на формат данных. Обычных описательных слов недостаточно:
Класс светораспределения (для светильников): Должен быть указан заглавными русскими буквами по ГОСТ Р 34819-2021: П, Н, Р, В или О.
Тип светораспределения (для прожекторов): Должен быть указан словами по ГОСТ Р 34819-2021: Узкое, Среднее или Широкое.
Тип кривой силы света (КСС): Должен быть указан буквенным кодом по ГОСТ Р 34819-2021: К, Г, Д, Л, Ш, М или С. Указание только градусов (например, "45°") — это ошибка классификации.
Номинальная КЦТ: Для белых светильников требуется строго 3000 К. Значения вроде "Теплый белый" или "4000 К" помечай как несоответствие.
Климатическое исполнение и температура: По требованиям нужно У1 по ГОСТ 15150-69 и диапазон от минус 40 до плюс 45 °С. Важно: Разрешается принимать исполнения, превосходящие У1 (например, УХЛ1, ХЛ1, В1, О1), при условии, что цифра категории размещения строго «1» (открытый воздух), а заявленный производителем температурный диапазон полностью включает в себя требуемый интервал (нижний порог не теплее -40°C, а верхний порог не холоднее +45°C). Если указано, например, УХЛ1 (от -60 до +40°C) — это ❌ Не соответствует, так как не дотягивает до верхнего предела.
Вибропрочность: Ищи маркировку группы механического исполнения не ниже М2 (ГОСТ 17516.1-90).
Ударопрочность: Ищи код IK05 или выше.

ФОРМАТ ВЫВОДА:
Сформируй результат проверки строго в виде правильной Markdown-таблицы.
Группируй параметры в смысловые блоки (например: "Светотехнические параметры", "Электротехнические параметры", "Конструкция"), чтобы таблица была компактной (10-15 строк).

СТРОГИЕ ПРАВИЛА ОФОРМЛЕНИЯ ТАБЛИЦЫ:
1. Каждая новая строка таблицы должна начинаться с символа переноса строки (Enter). Запрещено слеплять строки вместе!
2. Запрещено использовать символы `||` для разделения строк.
3. Обязательно нарисуй строку-разделитель после заголовков.

Шаблон таблицы:
| Блок параметров | Требование Ленсвета | Значение в паспорте | Статус |
|---|---|---|---|
| 1. Общие данные | ... | ... | ... |
| 2. Светотехнические | ... | ... | ... |

Статусы:
- "✅ Соответствует"
- "❌ Не соответствует" (обязательно укажи причину)
- "⚠️ Отсутствует информация"

После таблицы (с новой строки) напиши Краткий экспертный вывод:
1. Общая оценка: можно ли согласовать данный светильник.
2. Критические замечания: что производителю нужно срочно добавить или исправить.
"""


# ==========================================
# 4. ЛОГИКА ЗАГРУЗКИ И ПРОВЕРКИ
# ==========================================
with input_col:
    # Кладем загрузчик файла и кнопку тоже в узкую колонку
    uploaded_file = st.file_uploader("Загрузите паспорт (только PDF)", type=["pdf"])
    start_button = st.button("🚀 Начать проверку", use_container_width=True)

if uploaded_file is not None:
    if start_button:
        with st.spinner("Изучаю ГОСТы и анализирую документ..."):
            try:
                model = genai.GenerativeModel('gemini-2.5-flash')
                
                with tempfile.NamedTemporaryFile(delete=False, suffix=".pdf") as tmp:
                    tmp.write(uploaded_file.getvalue())
                    tmp_path = tmp.name
                    
                uploaded_pdf = genai.upload_file(path=tmp_path, mime_type="application/pdf")
                
                response = model.generate_content([system_prompt, uploaded_pdf])
                
                # Вывод ответа (таблицы) идет вне узкой колонки, 
                # поэтому он займет всю доступную ширину по центру (те самые комфортные ~730px)
                st.markdown("---")
                st.markdown(response.text)
                
                os.remove(tmp_path)
                
            except Exception as e:
                st.error(f"Произошла ошибка при обращении к API: {e}")
