import streamlit as st
import google.generativeai as genai
import tempfile
import os

# ==========================================
# 1. НАСТРОЙКИ БЕЗОПАСНОСТИ И ДОСТУПА
# ==========================================
# Вставь сюда свой реальный API-ключ внутри кавычек
MY_API_KEY = st.secrets["GEMINI_API_KEY"] 

# Придумай пароль для коллег
APP_PASSWORD = "MartiniMartini" 


# ==========================================
# 2. ИНТЕРФЕЙС И ПРОВЕРКА ПАРОЛЯ
# ==========================================
# ИЗМЕНЕНИЕ 1: Убрали layout="wide". Теперь страница центрирована и ограничена ~730px (как ширина чата)
st.set_page_config(page_title="Аудитор Ленсвет", page_icon="💡", layout="centered")
st.title("🕵️‍♂️ ИИ-Аудитор паспортов светильников")

# ИЗМЕНЕНИЕ 2: Создаем колонки. Левая (input_col) займет 2/3 от 730px (примерно 480px).
input_col, empty_col = st.columns([2, 1])

with input_col:
    # Кладем поле пароля в узкую колонку
    user_password = st.text_input("🔒 Введите пароль для доступа:", type="password")

# Шлагбаум пароля
if user_password != APP_PASSWORD:
    st.warning("Пожалуйста, введите верный пароль для начала работы.")
    st.stop() 

st.success("Доступ разрешен!")
st.write("Загрузите паспорт в формате PDF, и система проверит его на соответствие требованиям СПб ГБУ «Ленсвет».")


# ==========================================
# 3. НАСТРОЙКА API И ПРОМПТ
# ==========================================
genai.configure(api_key=MY_API_KEY)

system_prompt = """
Ты — строгий технический эксперт-аудитор. Твоя главная база знаний — объединенные технические требования СПб ГБУ «Ленсвет» и «Невский свет». Твоя задача — проверить предоставленный пользователем паспорт (или техническое описание) светодиодного светильника или прожектора для архитектурно-художественной подсветки на полное соответствие этим требованиям.

ПЕРВЫЙ ШАГ: Определи тип светильника — управляемый (например, DMX, DALI, RGBW) или без управления (статичный, on/off). От этого зависит проверка специального блока требований.
Для структурирования аудита обязательно используй следующий чек-лист:

1. Общие данные, документация и маркировка:
Номер модели.
Артикул: должен включать информацию о цвете светильника и типе подключения (сквозное / несквозное).
Цвет корпуса: определен по стандарту (RAL, RALd и др.). Внутренняя маркировка не допускается.
Документация: наличие руководства по монтажу.
Отметка о приемке: дата, подпись ответственного лица и печать при отгрузке.
Гарантия: от 5 лет.
Срок службы: 12 лет.
Ресурс: от 50 000 часов.

2. Конструкция и габариты:
Габаритные размеры.
Масса: не более 5 кг.
Присоединительные размеры к конструкциям (стене/кронштейнам).
Присоединительные размеры для аксессуаров (козырьков и т.д.).
Кронштейн: наличие механизма наклона (лира, скоба и т.д.).
Температура радиатора: не более 60°C.
Стекло: силикатное.
Степень защиты IP: IP66 (выше 1,5 м) или IP68 (в грунте/воде).
Разъем подключения: строго IP68 (если применяется).

3. Электротехнические параметры и кабели:
Напряжение: 230 В, 50 Гц; диапазон не хуже 176–264 В.
Мощность: потребляемая мощность с учетом потерь.
Отклонение мощности: указано, что не превышает номинал более чем на 10% (ГОСТ IEC 62722-1-2017).
Коэффициент мощности: до 8Вт — от 0,7; 8–20Вт — от 0,85; более 20Вт — от 0,90.
Пусковой ток: указаны амплитуда и длительность.
Источник питания: параметры (ном. ток, вх/вых напряжение).
Защита драйвера: от КЗ, ХХ, перегрев, гальваническая развязка.
Питающий кабель: указаны длина и марка, УФ-стойкий, черная оболочка.
Маркировка жил: информация на клеммах.
Класс защиты от поражения током: I (или III для грунтовых).

4. Светотехнические параметры:
Тип КСС: по ГОСТ Р 55392-2012 или указание углов раскрытия.
Номинальная КЦТ: строго 3000 К (для белых). "Теплый белый" или "4000 К" — несоответствие.
Энергоэффективность (световая отдача/поток): для прожекторов (узкое — от 65 Лм/Вт, среднее — от 85 Лм/Вт, широкое — от 95 Лм/Вт).
Коэффициент пульсации: не более 15%.
Снижение светового потока: не более 6%.
Индекс цветопередачи (Ra).

5. Климатическое исполнение и стойкость:
Климатическое исполнение: строго УХЛ1.
Температурный диапазон: от -40 до +45°C.
Вибропрочность: не ниже М2 (ГОСТ 17516.1-90).
Ударопрочность: IK05 или выше.

6. СПЕЦИАЛЬНЫЙ БЛОК: Для управляемых светильников (DMX и др.):
Если светильник "без управления", пропускай эти пункты, ставя статус "➖ Не применимо".
Кабель управления: указаны длина, марка, расположение выводов.
Поведение при обрыве: указан испускаемый цвет при отсутствии сигнала.
Адресация: указано количество занимаемых ячеек адресов.

ФОРМАТ ВЫВОДА:
Сформируй результат проверки строго в виде нескольких отдельных таблиц Markdown, разбитых по логическим блокам.
ВАЖНОЕ ПРАВИЛО: Каждый отдельный проверяемый параметр должен находиться в ОТДЕЛЬНОЙ строке. Не объединяй разные параметры! Не создавай колонку "Блок параметров".

Структура вывода:
Сначала напиши заголовок блока (используй ###), а строго под ним — таблицу из 4 колонок только для параметров этого блока.

Шаблон вывода:### 1. Общие данные, документация и маркировка
| Проверяемый параметр | Требование | Значение в паспорте | Статус |
|---|---|---|---|
| Артикул (цвет/тип) | Инфо о цвете и типе подключения | Указано (сквозное) | ✅ Соответствует |
| Гарантийный срок | От 5 лет | 5 лет | ✅ Соответствует |### 2. Конструкция и габариты
| Проверяемый параметр | Требование | Значение в паспорте | Статус |
|---|---|---|---|
| Масса | Не более 5 кг | Нет данных | ⚠️ Отсутствует информация |
| Степень защиты IP | IP66 или IP68 | IP66 | ✅ Соответствует |

*(...и так далее для всех логических блоков: 3. Электротехнические параметры, 4. Светотехнические параметры, 5. Климатическое исполнение, 6. Управление)*

Статусы:
- "✅ Соответствует"
- "❌ Не соответствует" (коротко укажи причину)
- "⚠️ Отсутствует информация"
- "➖ Не применимо"

После всех таблиц (с новой строки) напиши Краткий экспертный вывод:
1. Тип светильника: (укажи, управляемый или статичный).
2. Общая оценка: можно ли согласовать данный светильник.
3. Критические замечания: что производителю нужно срочно добавить или исправить.
"""


# ==========================================
# 4. ЛОГИКА ЗАГРУЗКИ И ПРОВЕРКИ
# ==========================================
with input_col:
    # Кладем загрузчик файла и кнопку тоже в узкую колонку
    uploaded_file = st.file_uploader("Загрузите паспорт (только PDF)", type=["pdf"])
    start_button = st.button("🚀 Начать проверку", use_container_width=True)

if uploaded_file is not None:
    if start_button:
        with st.spinner("Изучаю ГОСТы и анализирую документ..."):
            try:
                model = genai.GenerativeModel('gemini-2.5-flash')
                
                with tempfile.NamedTemporaryFile(delete=False, suffix=".pdf") as tmp:
                    tmp.write(uploaded_file.getvalue())
                    tmp_path = tmp.name
                    
                uploaded_pdf = genai.upload_file(path=tmp_path, mime_type="application/pdf")
                
                response = model.generate_content([system_prompt, uploaded_pdf])
                
                # Вывод ответа (таблицы) идет вне узкой колонки, 
                # поэтому он займет всю доступную ширину по центру (те самые комфортные ~730px)
                st.markdown("---")
                st.markdown(response.text)
                
                os.remove(tmp_path)
                
            except Exception as e:
                st.error(f"Произошла ошибка при обращении к API: {e}")
